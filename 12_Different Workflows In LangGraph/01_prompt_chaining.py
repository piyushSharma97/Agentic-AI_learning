"""
=============================================================================
TOPIC 109 & 110: PROMPT CHAINING WORKFLOW IN LANGGRAPH
=============================================================================

1. WHAT IS PROMPT CHAINING? (Topic 109)
---------------------------------------
Prompt Chaining is a foundational workflow pattern where a complex task is
decomposed into a fixed sequence of smaller, highly focused LLM calls.
The output of Step N becomes the input (or part of the context) for Step N+1.

    [User Prompt]
          │
          ▼
    ┌───────────────┐
    │ Node 1: Plan  │ (Creates structured outline)
    └───────┬───────┘
            │
            ▼  (Gate / Validation Check)
    ┌───────────────┐
    │ Node 2: Draft │ (Writes detailed content based on outline)
    └───────┬───────┘
            │
            ▼
    ┌───────────────┐
    │ Node 3: Polish│ (Refines, formats, checks guidelines)
    └───────┬───────┘
            │
            ▼
     [Final Output]

2. WHY NOT A SINGLE MEGA-PROMPT?
--------------------------------
- "Cognitive Load": Asking an LLM to outline, write, fact-check, and format
  all in one turn degrades output quality and increases hallucinations.
- "Gate Checks": Prompt chaining allows programmatic validation between steps
  (e.g., if the outline doesn't have at least 3 sections, don't waste tokens
  drafting; ask for revision or halt).
- "Separation of Concerns": Each step can use tailored system prompts,
  different temperatures, or even different specialized models.

3. LANGGRAPH IMPLEMENTATION (Topic 110)
---------------------------------------
In LangGraph, Prompt Chaining is modeled as:
- A TypedDict State holding intermediate results: outline, draft, polished output.
- Linear sequential edges: Node A -> Node B -> Node C.
- Optional conditional gate edges between nodes.
=============================================================================
"""

from typing import TypedDict, Optional
from langgraph.graph import StateGraph, START, END
from langchain_core.messages import SystemMessage, HumanMessage

from config import get_llm, print_mermaid, print_banner, safe_run


# =============================================================================
# 1. STATE DEFINITION
# =============================================================================
class ChainingState(TypedDict):
    """
    State tracks the evolving document through each sequential transformation.
    Each node populates or updates its respective field.
    """
    topic: str                     # Initial user input topic
    target_audience: str           # Target reader persona
    outline: Optional[str]         # Generated by Node 1
    draft: Optional[str]           # Generated by Node 2
    final_post: Optional[str]      # Generated by Node 3
    outline_approved: bool         # Gate flag checked between Node 1 & Node 2


# =============================================================================
# 2. NODE IMPLEMENTATIONS
# =============================================================================
llm = get_llm(temperature=0.3)


def generate_outline_node(state: ChainingState) -> dict:
    """
    Step 1: Ideation & Structure Node.
    Creates a clear, 3-section outline for the requested topic.
    """
    print("[Node 1: Outline] Generating structured outline...")

    prompt = f"""You are a technical content strategist.
Create a concise, structured 3-point outline for a blog post on the topic: '{state['topic']}'.
Target Audience: {state['target_audience']}.
Include only section titles and brief 1-sentence bullet points for each section."""

    response = llm.invoke([
        SystemMessage(content="You create clear, bulleted technical outlines."),
        HumanMessage(content=prompt)
    ])

    outline_text = response.content.strip()

    # Programmatic quality gate: check that outline is non-empty and has content
    is_valid = len(outline_text) > 50 and ("1." in outline_text or "-" in outline_text or "Section" in outline_text)

    return {
        "outline": outline_text,
        "outline_approved": is_valid
    }


def write_draft_node(state: ChainingState) -> dict:
    """
    Step 2: Drafting Node.
    Consumes the outline from Step 1 and writes the complete blog draft.
    """
    print("[Node 2: Draft] Writing comprehensive draft based on outline...")

    prompt = f"""You are a senior technical writer.
Topic: {state['topic']}
Target Audience: {state['target_audience']}

Follow this outline strictly to write a cohesive 2-paragraph educational blog draft:
{state['outline']}"""

    response = llm.invoke([
        SystemMessage(content="You write engaging, informative technical articles."),
        HumanMessage(content=prompt)
    ])

    return {"draft": response.content.strip()}


def polish_and_format_node(state: ChainingState) -> dict:
    """
    Step 3: Polishing & Formatting Node.
    Consumes the draft from Step 2, adds a catchy title, key takeaways, and hashtags.
    """
    print("[Node 3: Polish] Polishing tone, adding title and key takeaways...")

    prompt = f"""Review and polish the following draft for {state['target_audience']}.
Add:
1. A compelling Title
2. The polished text with clear formatting
3. Three bulleted 'Key Takeaways' at the bottom
4. Three relevant hashtags

Draft to polish:
{state['draft']}"""

    response = llm.invoke([
        SystemMessage(content="You are an expert editor who enhances readability and polish."),
        HumanMessage(content=prompt)
    ])

    return {"final_post": response.content.strip()}


# =============================================================================
# 3. GATE / CONDITIONAL ROUTING (Topic 110 Gate Concept)
# =============================================================================
def outline_gate_condition(state: ChainingState) -> str:
    """
    Checks if Node 1 produced a valid, approved outline.
    If valid -> proceed to drafting.
    If invalid -> terminate early to save tokens and prevent poor drafts.
    """
    if state.get("outline_approved", False):
        return "write_draft"
    print("[Gate Warning] Outline failed quality criteria. Halting workflow.")
    return END


# =============================================================================
# 4. GRAPH ASSEMBLY & TOPOLOGY
# =============================================================================
builder = StateGraph(ChainingState)

# Add sequential processing nodes
builder.add_node("generate_outline", generate_outline_node)
builder.add_node("write_draft", write_draft_node)
builder.add_node("polish_and_format", polish_and_format_node)

# Wire the graph:
# START -> generate_outline
builder.add_edge(START, "generate_outline")

# Conditional Edge (Quality Gate between Step 1 and Step 2):
builder.add_conditional_edges(
    "generate_outline",
    outline_gate_condition,
    {
        "write_draft": "write_draft",
        END: END
    }
)

# write_draft -> polish_and_format -> END
builder.add_edge("write_draft", "polish_and_format")
builder.add_edge("polish_and_format", END)

# Compile into executable runnable
chain_graph = builder.compile()


# =============================================================================
# 5. DEMO EXECUTION
# =============================================================================
def run_prompt_chaining_demo():
    print_banner(
        "TOPIC 109 & 110",
        "Prompt Chaining Workflow",
        "Demonstrates a 3-stage sequential chain with a programmatic quality gate:\n"
        "1. Generate Outline -> 2. Quality Gate -> 3. Write Draft -> 4. Polish & Format"
    )

    # Print Mermaid visualization
    print_mermaid(chain_graph, "Prompt Chaining Topology")

    initial_input: ChainingState = {
        "topic": "Why Agents Need Memory (Checkpointers in LangGraph)",
        "target_audience": "Software engineers learning Agentic AI",
        "outline": None,
        "draft": None,
        "final_post": None,
        "outline_approved": False
    }

    print(f"Initial Topic: '{initial_input['topic']}'")
    print(f"Target Audience: '{initial_input['target_audience']}'\n")

    # Run the graph
    result = chain_graph.invoke(initial_input)

    # Display Intermediate & Final Results
    print("\n" + "=" * 60)
    print("STAGE 1: GENERATED OUTLINE")
    print("=" * 60)
    print(result["outline"])

    print("\n" + "=" * 60)
    print("STAGE 2: RAW DRAFT")
    print("=" * 60)
    print(result["draft"])

    print("\n" + "=" * 60)
    print("STAGE 3: FINAL POLISHED POST")
    print("=" * 60)
    print(result["final_post"])


if __name__ == "__main__":
    safe_run("Prompt Chaining Workflow", run_prompt_chaining_demo)
