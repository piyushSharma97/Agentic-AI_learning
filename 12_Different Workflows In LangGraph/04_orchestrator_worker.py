"""
=============================================================================
TOPIC 113 & 114: ORCHESTRATOR-WORKER PATTERN IN LANGGRAPH
=============================================================================

1. WHAT IS THE ORCHESTRATOR-WORKER PATTERN? (Topic 113)
-------------------------------------------------------
In Prompt Chaining and Parallelization, the execution graph is hardcoded
ahead of time (fixed nodes and fixed edges).

In the Orchestrator-Worker pattern, the workflow is DYNAMIC:
A central Orchestrator LLM breaks down a complex goal into dynamic sub-tasks
at runtime, assigns them to Worker nodes, and a Synthesizer combines them.

                    ┌───────────────────────────────┐
                    │      ORCHESTRATOR NODE        │
                    │   (Analyzes goal & dynamically│
                    │    plans K specific subtasks) │
                    └───────────────┬───────────────┘
                                    │
           ┌────────────────────────┼────────────────────────┐
           ▼                        ▼                        ▼
     ┌───────────┐            ┌───────────┐            ┌───────────┐
     │ Worker 1  │            │ Worker 2  │            │ Worker 3  │
     │(Subtask 1)│            │(Subtask 2)│            │(Subtask 3)│
     └─────┬─────┘            └─────┬─────┘            └─────┬─────┘
           │                        │                        │
           └────────────────────────┼────────────────────────┘
                                    ▼
                    ┌───────────────────────────────┐
                    │       SYNTHESIZER NODE        │
                    │   (Compiles all worker outputs│
                    │    into a final deliverable)  │
                    └───────────────────────────────┘

2. WHEN TO USE ORCHESTRATOR-WORKER?
-----------------------------------
- Unknown Subtasks Ahead of Time: The exact steps depend on the user's specific request.
  (e.g., "Build a full marketing launch for an AI fitness app" vs. "Launch an open-source database").
- Complex Multi-Perspective Research: Writing technical documentation across
  architecture, API endpoints, and database models.
- Task Delegation & Modularity: Individual workers focus on narrow sub-problems
  with dedicated instructions and context.

3. LANGGRAPH IMPLEMENTATION (Topic 114)
---------------------------------------
- Orchestrator Node generates a structured list of tasks: `[{"id": 1, "topic": ..., "instruction": ...}]`.
- Worker Node processes the tasks and appends completed artifacts into state.
- Synthesizer Node takes all worker deliverables and stitches them into a cohesive master document.
=============================================================================
"""

import json
import operator
from typing import Annotated, Dict, List, TypedDict
from langgraph.graph import StateGraph, START, END
from langchain_core.messages import SystemMessage, HumanMessage

from config import get_llm, print_mermaid, print_banner, safe_run


# =============================================================================
# 1. STATE DEFINITION
# =============================================================================
class SubTask(TypedDict):
    task_id: int
    title: str
    instruction: str


class CompletedSubTask(TypedDict):
    task_id: int
    title: str
    output: str


class OrchestratorState(TypedDict):
    """
    State tracks the overall objective, dynamic subtask plan, completed worker outputs,
    and the final synthesized deliverable.
    """
    objective: str                                                         # High-level user goal
    plan: List[SubTask]                                                    # Dynamic subtasks generated by Orchestrator
    worker_results: Annotated[List[CompletedSubTask], operator.add]        # Collected worker results
    final_deliverable: str                                                 # Synthesized master deliverable


# =============================================================================
# 2. ORCHESTRATOR NODE (DYNAMIC PLANNING)
# =============================================================================
llm = get_llm(temperature=0.2)


def orchestrator_node(state: OrchestratorState) -> dict:
    """
    Topic 113 & 114 Core:
    Dynamically analyzes the user's objective and decomposes it into 3 specific,
    actionable subtasks with tailored instructions.
    """
    print("[Orchestrator] Analyzing objective and generating dynamic subtasks...")

    prompt = f"""You are a Master Project Manager & Technical Orchestrator.
Objective: "{state['objective']}"

Break this objective down into EXACTLY 3 focused, non-overlapping subtasks.
Return ONLY valid JSON in this exact structure:
[
  {{"task_id": 1, "title": "Subtask title", "instruction": "Clear 1-sentence prompt for worker"}},
  {{"task_id": 2, "title": "Subtask title", "instruction": "Clear 1-sentence prompt for worker"}},
  {{"task_id": 3, "title": "Subtask title", "instruction": "Clear 1-sentence prompt for worker"}}
]"""

    response = llm.invoke([
        SystemMessage(content="You break complex goals into structured JSON plans."),
        HumanMessage(content=prompt)
    ])

    raw_text = response.content.strip()

    # Clean markdown backticks if present
    if raw_text.startswith("```"):
        raw_text = raw_text.strip("`")
        if raw_text.startswith("json"):
            raw_text = raw_text[4:].strip()

    try:
        plan: List[SubTask] = json.loads(raw_text)
    except Exception as e:
        print(f"[Orchestrator Warning] JSON parsing error: {e}. Using fallback plan.")
        plan = [
            {"task_id": 1, "title": "Architecture Design", "instruction": "Design system architecture."},
            {"task_id": 2, "title": "API Specification", "instruction": "Specify core API endpoints."},
            {"task_id": 3, "title": "Security & Monitoring", "instruction": "Outline security guidelines."}
        ]

    print(f"[Orchestrator] Successfully planned {len(plan)} dynamic subtasks:")
    for task in plan:
        print(f"  Task {task['task_id']}: {task['title']}")

    return {"plan": plan}


# =============================================================================
# 3. WORKER NODE (TASK EXECUTION)
# =============================================================================
def workers_execution_node(state: OrchestratorState) -> dict:
    """
    Executes each planned subtask.
    In production, workers can run in parallel; here we iterate over the dynamic plan,
    invoking the LLM with the tailored instruction for each task.
    """
    print("\n[Workers] Executing planned subtasks...")
    completed_tasks: List[CompletedSubTask] = []

    for task in state["plan"]:
        print(f"  -> Worker assigned to Task {task['task_id']}: '{task['title']}'...")

        worker_prompt = f"""You are a specialized execution worker.
Overall Goal: {state['objective']}
Your Assigned Subtask: {task['title']}
Instructions: {task['instruction']}

Write a concise, high-impact 2-3 paragraph deliverable specifically fulfilling your instructions."""

        response = llm.invoke([
            SystemMessage(content=f"You are a specialist worker focused on {task['title']}."),
            HumanMessage(content=worker_prompt)
        ])

        completed_tasks.append({
            "task_id": task["task_id"],
            "title": task["title"],
            "output": response.content.strip()
        })

    return {"worker_results": completed_tasks}


# =============================================================================
# 4. SYNTHESIZER NODE (AGGREGATION)
# =============================================================================
def synthesizer_node(state: OrchestratorState) -> dict:
    """
    Synthesizes the worker outputs into a single cohesive, polished executive document.
    """
    print("\n[Synthesizer] Compiling all worker outputs into Final Master Deliverable...")

    sections_text = ""
    for item in state["worker_results"]:
        sections_text += f"\n### Section {item['task_id']}: {item['title']}\n{item['output']}\n"

    prompt = f"""You are a Senior Technical Director.
Overall Objective: "{state['objective']}"

Here are the deliverables produced by your specialized workers:
{sections_text}

Assemble these sections into a cohesive, professional Executive Technical Report.
Include:
1. Executive Summary (2 sentences)
2. The synthesized sections with clean formatting
3. Next Steps / Implementation Roadmap (3 bullet points)"""

    response = llm.invoke([
        SystemMessage(content="You write seamless, executive-ready consolidated reports."),
        HumanMessage(content=prompt)
    ])

    return {"final_deliverable": response.content.strip()}


# =============================================================================
# 5. GRAPH ASSEMBLY & TOPOLOGY
# =============================================================================
builder = StateGraph(OrchestratorState)

builder.add_node("orchestrator", orchestrator_node)
builder.add_node("workers", workers_execution_node)
builder.add_node("synthesizer", synthesizer_node)

# Flow: START -> orchestrator -> workers -> synthesizer -> END
builder.add_edge(START, "orchestrator")
builder.add_edge("orchestrator", "workers")
builder.add_edge("workers", "synthesizer")
builder.add_edge("synthesizer", END)

orchestrator_graph = builder.compile()


# =============================================================================
# 6. DEMO EXECUTION
# =============================================================================
def run_orchestrator_worker_demo():
    print_banner(
        "TOPIC 113 & 114",
        "Orchestrator-Worker Pattern",
        "Demonstrates dynamic runtime task planning by an Orchestrator,\n"
        "delegated execution by Workers, and final aggregation by a Synthesizer."
    )

    print_mermaid(orchestrator_graph, "Orchestrator-Worker Topology")

    goal = "Design an automated, low-latency Audio-to-Summary pipeline for customer support calls."
    print(f"User Goal: \"{goal}\"\n")

    initial_input: OrchestratorState = {
        "objective": goal,
        "plan": [],
        "worker_results": [],
        "final_deliverable": ""
    }

    result = orchestrator_graph.invoke(initial_input)

    print("\n" + "=" * 65)
    print("INDIVIDUAL WORKER OUTPUTS:")
    print("=" * 65)
    for res in result["worker_results"]:
        print(f"\n[Task {res['task_id']}: {res['title']}]")
        print(res["output"])
        print("-" * 50)

    print("\n" + "=" * 65)
    print("FINAL SYNTHESIZED DELIVERABLE:")
    print("=" * 65)
    print(result["final_deliverable"])


if __name__ == "__main__":
    safe_run("Orchestrator-Worker Workflow", run_orchestrator_worker_demo)
