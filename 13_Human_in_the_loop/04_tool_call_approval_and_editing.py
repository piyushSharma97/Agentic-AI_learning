"""
=============================================================================
LESSON 04: TOOL CALL APPROVAL, EDITING & REJECTION (HUMAN-IN-THE-LOOP PATTERN)
=============================================================================

1. THE PROBLEM:
-----------------------------------------------------------------------------
Autonomous AI agents can take impactful real-world actions:
- Transferring money
- Writing or deleting records in a database
- Sending emails or API calls
You cannot let the agent run completely unattended when high-stakes tools
are involved.

2. THE ENTERPRISE APPROVAL PATTERN:
-----------------------------------------------------------------------------
Compile the graph with:
  `interrupt_before=["tools"]`

When the agent decides to execute a tool, execution halts. The human reviews:
  Tool Name: `multiply`
  Arguments: `{'a': 25, 'b': 4}`

The human has 3 choices:
  [A] APPROVE : Execute the tool as is -> `graph.stream(None, thread)`.
  [E] EDIT    : Modify the arguments in-place before executing (e.g. change a=25 to a=50).
  [R] REJECT  : Deny execution! Instead of running the tool, inject a ToolMessage
                stating "Action rejected by user.", allowing the assistant to
                gracefully handle the refusal without executing the tool.

3. HOW TO PROPERLY REJECT A TOOL CALL IN LANGGRAPH:
-----------------------------------------------------------------------------
Every tool call has a unique `id` generated by the model (e.g., `call_123` or `fc_xyz`).
When rejecting:
1. Do NOT let the `tools` node run.
2. Inject a `ToolMessage` with `tool_call_id=tool_call["id"]` and content="Tool execution denied by user."
3. Update state as if the tool finished (`as_node="tools"`).
4. Resume assistant to generate its apology or fallback response!
=============================================================================
"""

from typing import Dict, Any, List
from langgraph.checkpoint.memory import MemorySaver
from langgraph.graph import MessagesState, StateGraph, START, END
from langgraph.prebuilt import ToolNode, tools_condition
from langchain_core.messages import HumanMessage, AIMessage, ToolMessage, SystemMessage

from config import get_llm, COMMON_TOOLS, print_banner, inspect_state_snapshot


def build_tool_approval_graph():
    """Builds a checkpointer-backed arithmetic graph interrupted before tools."""
    llm = get_llm()
    llm_with_tools = llm.bind_tools(COMMON_TOOLS)

    sys_msg = SystemMessage(
        content="You are a financial and arithmetic assistant. Always call tools to perform math calculations."
    )

    def assistant(state: MessagesState) -> Dict[str, Any]:
        response = llm_with_tools.invoke([sys_msg] + state["messages"])
        return {"messages": [response]}

    builder = StateGraph(MessagesState)
    builder.add_node("assistant", assistant)
    builder.add_node("tools", ToolNode(COMMON_TOOLS))

    builder.add_edge(START, "assistant")
    builder.add_conditional_edges("assistant", tools_condition)
    builder.add_edge("tools", "assistant")

    memory = MemorySaver()
    return builder.compile(checkpointer=memory, interrupt_before=["tools"])


def demo_approve_tool_call():
    """CASE 1: Human Approves Tool Call (Runs as planned)."""
    print_banner(
        "LESSON 04 - CASE 1",
        "Action: APPROVE Tool Call",
        "Agent proposes tool call -> Human reviews -> Human approves -> Tool runs."
    )
    graph = build_tool_approval_graph()
    thread = {"configurable": {"thread_id": "thread-approval-case-1"}}

    # Trigger tool call
    initial_input = {"messages": [HumanMessage(content="Calculate 25 multiplied by 4.")]}
    for _ in graph.stream(initial_input, thread, stream_mode="values"):
        pass

    state = graph.get_state(thread)
    tool_call = state.values["messages"][-1].tool_calls[0]
    print(f"Proposed Tool: {tool_call['name']}({tool_call['args']})")
    print("Human Decision: [A] APPROVE")

    # Resume by passing None
    for event in graph.stream(None, thread, stream_mode="values"):
        msg = event["messages"][-1]
        if msg.__class__.__name__ == "ToolMessage":
            print(f"  Tool Executed: {msg.content}")
        elif msg.__class__.__name__ == "AIMessage" and msg.content:
            print(f"  Final Response: {msg.content}")


def demo_edit_tool_arguments():
    """CASE 2: Human Edits Tool Arguments in-place before execution."""
    print_banner(
        "LESSON 04 - CASE 2",
        "Action: EDIT Tool Call Arguments",
        "Agent proposes tool call -> Human alters parameters -> Tool runs with revised values."
    )
    graph = build_tool_approval_graph()
    thread = {"configurable": {"thread_id": "thread-approval-case-2"}}

    initial_input = {"messages": [HumanMessage(content="Calculate 25 multiplied by 4.")]}
    for _ in graph.stream(initial_input, thread, stream_mode="values"):
        pass

    state = graph.get_state(thread)
    last_ai_msg = state.values["messages"][-1]
    original_call = last_ai_msg.tool_calls[0]
    print(f"Original Proposed Tool: {original_call['name']}({original_call['args']})")
    
    print("Human Decision: [E] EDIT arguments to a=50, b=4")
    # Replace tool call args while keeping the same message ID
    edited_tool_call = dict(original_call)
    edited_tool_call["args"] = {"a": 50, "b": 4}

    edited_ai_msg = AIMessage(
        id=last_ai_msg.id,
        content=last_ai_msg.content,
        tool_calls=[edited_tool_call],
    )
    graph.update_state(thread, {"messages": [edited_ai_msg]}, as_node="assistant")

    # Resume execution with edited arguments
    for event in graph.stream(None, thread, stream_mode="values"):
        msg = event["messages"][-1]
        if msg.__class__.__name__ == "ToolMessage":
            print(f"  Tool Executed with Edited Args: {msg.content} (Expected: 200)")
        elif msg.__class__.__name__ == "AIMessage" and msg.content:
            print(f"  Final Response: {msg.content}")


def demo_reject_tool_call():
    """CASE 3: Human Rejects Tool Call (Blocks tool execution safely)."""
    print_banner(
        "LESSON 04 - CASE 3",
        "Action: REJECT Tool Call",
        "Agent proposes tool call -> Human denies permission -> Injects denial message -> AI handles refusal."
    )
    graph = build_tool_approval_graph()
    thread = {"configurable": {"thread_id": "thread-approval-case-3"}}

    initial_input = {"messages": [HumanMessage(content="Calculate 25 multiplied by 4.")]}
    for _ in graph.stream(initial_input, thread, stream_mode="values"):
        pass

    state = graph.get_state(thread)
    last_ai_msg = state.values["messages"][-1]
    tool_call = last_ai_msg.tool_calls[0]
    print(f"Proposed Tool: {tool_call['name']}({tool_call['args']})")

    print("Human Decision: [R] REJECT tool execution!")

    # In LangGraph, when rejecting a tool call, we fulfill the tool call expectation
    # by providing a ToolMessage with an error / denial explanation, attributing it to 'tools'
    rejection_msg = ToolMessage(
        tool_call_id=tool_call["id"],
        content="Action Denied: The user declined permission to execute this calculation tool.",
        name=tool_call["name"],
    )

    # We update the state as if the tools node resolved it
    graph.update_state(thread, {"messages": [rejection_msg]}, as_node="tools")

    print("State updated with human rejection notice. Resuming assistant to handle refusal...")
    for event in graph.stream(None, thread, stream_mode="values"):
        msg = event["messages"][-1]
        if msg.__class__.__name__ == "AIMessage" and msg.content:
            print(f"\nAssistant Graceful Response:\n{msg.content}")


if __name__ == "__main__":
    demo_approve_tool_call()
    demo_edit_tool_arguments()
    demo_reject_tool_call()
