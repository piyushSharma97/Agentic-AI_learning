"""
=============================================================================
USE CASE 4: TOOL CALLING IN LANGCHAIN
=============================================================================
Tool Calling (formerly Function Calling) is the bridge between LLM reasoning
and real-world capabilities: APIs, databases, math solvers, and file systems.

Crucial Concept:
LLMs do NOT run Python code or make HTTP requests directly!
1. The developer registers a tool schema with the LLM via `bind_tools`.
2. The LLM detects when a question needs a tool and responds with a
   structured `tool_calls` payload (function name + JSON arguments).
3. The application executes the function locally in Python.
4. The application returns the output as a `ToolMessage`.
5. The LLM reads the tool output and synthesizes the final user response.

Key Concepts Covered:
1. Creating type-safe tools with the `@tool` decorator
2. Binding tools to chat models with `llm.bind_tools(...)`
3. Inspecting `ai_msg.tool_calls`
4. Executing tools and feeding results back via `ToolMessage`
5. Parallel and multi-tool invocations
=============================================================================
"""

import json
from typing import Dict, Any
from langchain_core.tools import tool
from langchain_core.messages import HumanMessage, AIMessage, ToolMessage

# Import shared LLM config
from config import get_llm, safe_execute


# ---------------------------------------------------------------------------
# 1. Define Tools using the @tool Decorator
# ---------------------------------------------------------------------------
@tool
def get_current_stock_price(ticker: str) -> str:
    """
    Fetch the latest market stock price for a given ticker symbol.
    
    Args:
        ticker: The stock ticker symbol (e.g. 'AAPL', 'GOOGL', 'NVDA', 'TSLA').
    """
    # Simulated stock database / API response
    database = {
        "AAPL": {"price": 228.50, "currency": "USD", "change": "+1.4%"},
        "GOOGL": {"price": 178.20, "currency": "USD", "change": "-0.3%"},
        "NVDA": {"price": 139.80, "currency": "USD", "change": "+3.8%"},
        "TSLA": {"price": 242.10, "currency": "USD", "change": "+0.9%"},
    }
    ticker_clean = ticker.upper().strip()
    data = database.get(ticker_clean)
    if data:
        return json.dumps({"ticker": ticker_clean, **data})
    return json.dumps({"error": f"Ticker '{ticker_clean}' not found in database."})


@tool
def calculate_portfolio_value(shares: float, price_per_share: float) -> str:
    """
    Multiply the number of shares by the price per share to calculate total holding value.
    
    Args:
        shares: Number of stock shares owned.
        price_per_share: Current price of one single share.
    """
    total = shares * price_per_share
    return json.dumps({"total_value_usd": round(total, 2)})


# ---------------------------------------------------------------------------
# 2. Inspecting Tool Schemas Generated by LangChain
# ---------------------------------------------------------------------------
def demo_inspect_tool_schema():
    print("--- 1. Inspecting Tool Schemas sent to LLMs ---")
    print(f"Tool Name: {get_current_stock_price.name}")
    print(f"Tool Description: {get_current_stock_price.description}")
    print(f"Tool Input Schema:\n{json.dumps(get_current_stock_price.args, indent=2)}\n")


# ---------------------------------------------------------------------------
# 3. Complete Tool Calling Lifecycle (Request -> Call -> Execute -> Synthesize)
# ---------------------------------------------------------------------------
def demo_tool_calling_lifecycle():
    print("--- 2. End-to-End Tool Calling Loop ---")
    llm = get_llm()
    
    # 1. Register tools with the model
    tools = [get_current_stock_price, calculate_portfolio_value]
    tools_by_name = {t.name: t for t in tools}
    llm_with_tools = llm.bind_tools(tools)
    
    # 2. User query requiring real-time external data
    user_query = "What is the stock price of NVDA right now, and how much would 50 shares be worth?"
    messages = [HumanMessage(content=user_query)]
    print(f"User: {user_query}")
    
    # 3. Model decides whether to call tools
    ai_msg: AIMessage = llm_with_tools.invoke(messages)
    messages.append(ai_msg)
    
    print("\n--- Model Decision ---")
    print(f"Content: {ai_msg.content or '(Empty content, issued tool calls)'}")
    print(f"Tool Calls Detected: {len(ai_msg.tool_calls)}")
    
    # 4. Execute tool calls generated by the model
    for call in ai_msg.tool_calls:
        tool_name = call["name"]
        tool_args = call["args"]
        call_id = call["id"]
        
        print(f"\n[Executing Tool]: {tool_name} with arguments {tool_args}")
        selected_tool = tools_by_name.get(tool_name)
        
        if selected_tool:
            tool_output = selected_tool.invoke(tool_args)
            print(f"[Tool Raw Output]: {tool_output}")
            
            # Package result as ToolMessage referencing the tool_call_id
            messages.append(ToolMessage(content=str(tool_output), tool_call_id=call_id))
        else:
            print(f"Error: Unknown tool {tool_name}")

    # 5. Send conversation + tool output back to LLM for final synthesis
    print("\n--- Final Synthesis from LLM ---")
    final_response = llm_with_tools.invoke(messages)
    print(f"Assistant: {final_response.content}\n")


# ---------------------------------------------------------------------------
# MAIN EXECUTION
# ---------------------------------------------------------------------------
def main():
    safe_execute("Tool Calling Demonstrations", lambda: [
        demo_inspect_tool_schema(),
        demo_tool_calling_lifecycle(),
    ])


if __name__ == "__main__":
    main()

