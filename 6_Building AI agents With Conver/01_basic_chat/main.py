"""
Lesson 1: Basic Chat — Sending Single Messages to a Chat Model

What you will learn in this lesson:
1. How to load API keys securely from a local .env file.
2. How to initialize ChatGroq for ultra-fast cloud LLM inference.
3. How to use HumanMessage to format user input in LangChain.
4. How to call model.invoke() and inspect the returned AIMessage.
"""

import os
# os provides access to environment variables such as GROQ_API_KEY.
from dotenv import load_dotenv
# python-dotenv parses a .env file and sets the variables in os.environ.
from langchain_core.messages import HumanMessage
# HumanMessage represents input originating from a human user.
from langchain_groq import ChatGroq
# ChatGroq integrates LangChain with Groq's high-speed inference engine.

# --------------------------------------------------
# 1. Environment Configuration
# --------------------------------------------------

# Load settings from .env into process environment.
load_dotenv()

api_key = os.getenv("GROQ_API_KEY")
model_name = os.getenv("GROQ_MODEL", "llama-3.3-70b-versatile")

# Validate that the API key exists before attempting network calls.
if not api_key:
    raise RuntimeError("Add GROQ_API_KEY to your .env file.")

# --------------------------------------------------
# 2. Model Initialization
# --------------------------------------------------

# Create the model client.
# Note: Initializing the class does not call the API or incur token costs yet.
model = ChatGroq(model=model_name, groq_api_key=api_key)

# --------------------------------------------------
# 3. Sending a Message & Receiving a Response
# --------------------------------------------------

# Chat models expect a list of message objects.
# Here we send a single HumanMessage containing our prompt.
response = model.invoke([
    HumanMessage(content="Explain what an LLM is in two simple sentences.")
])

# invoke() returns an AIMessage object containing metadata (token usage, finish reason) and the answer.
# .content extracts just the plain text generated by the model.
print(response.content)

