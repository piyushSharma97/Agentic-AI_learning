# 2. CREATE A TOOL USING THE @tool DECORATOR

from langchain.tools import tool


@tool
def get_weather(location: str) -> str:
    """
    Get the weather information for a given location.

    Args:
        location: Name of the city.

    Returns:
        Weather information as a string.
    """

    # This is mock data for demonstration.
    # A real implementation would call a weather API.
    return f"It's sunny in {location}."


# 3. MANUAL TOOL-CALLING LOOP

from langchain.chat_models import init_chat_model
from langchain_core.messages import HumanMessage


def example_1_manual_tool_call():

    if not os.getenv("GROQ_API_KEY"):
        raise ValueError("GROQ_API_KEY is missing from .env")

    print("\n========== EXAMPLE 1: MANUAL TOOL CALL ==========")

    # Initialize the Groq-hosted model.
    # Use a model ID currently supported by your Groq account.
    tool_chat_model = init_chat_model("groq:openai/gpt-oss-120b")

    # bind_tools() provides the LLM with the available tool
    # definitions, including their names, descriptions and schemas.
    #
    # It does NOT execute the Python functions.
    # The model only generates a request to call a tool.

    model_with_tools = tool_chat_model.bind_tools([get_weather])

    # Create the initial conversation message.
    weather_messages = [
        HumanMessage(
            content="What's the weather like in Boston?"
        )
    ]

    # Invoke the model.
    # The model decides whether a tool is required.
    weather_ai_message = model_with_tools.invoke(weather_messages)
    print(
        "[Example 1 | manual tool call] Tool calls:",
        weather_ai_message.tool_calls
    )

    # Store the AI response in conversation history.
    # This response may contain one or more tool calls.

    weather_messages.append(weather_ai_message)

    print(
        "[Example 1 | manual tool call] Messages after AI append:",
        weather_messages
    )
    print(
        "[Example 1 | manual tool call] Messages type:",
        type(weather_messages)
    )

    # Create a dictionary to map tool names to Python functions.
    # This is useful when multiple tools are registered.

    weather_tools_by_name = {
        "get_weather": get_weather
    }

    # Check whether the model requested any tools.
    if weather_ai_message.tool_calls:

        # A model can request multiple tool calls.
        for tool_call in weather_ai_message.tool_calls:

            # Extract the requested tool name.
            tool_name = tool_call["name"]

            # Extract the arguments generated by the model.
            tool_args = tool_call["args"]

            print("[Example 1 | manual tool call] Tool requested:", tool_name)
            print("[Example 1 | manual tool call] Tool arguments:", tool_args)

            # Find the corresponding Python function.
            selected_tool = weather_tools_by_name.get(tool_name)

            # Validate that the requested tool exists.
            if selected_tool is None:
                raise ValueError(f"Unknown tool: {tool_name}")

            # Execute the Python function.
            #
            # The tool_call dictionary includes the tool name,
            # arguments and tool-call ID.
            #
            # LangChain returns a ToolMessage containing the result.

            tool_result = selected_tool.invoke(tool_call)

            # Add the tool execution result to conversation history.
            # The model needs this result to generate its final answer.
            weather_messages.append(tool_result)

            print("[Example 1 | manual tool call] Tool result:", tool_result.content)

        # The model now receives:
        # 1. Original user message.
        # 2. Its own tool-call request.
        # 3. Tool execution result.
        #
        # It uses this information to generate the final response.

        weather_final_response = model_with_tools.invoke(weather_messages)

        print(
            "[Example 1 | manual tool call] Final reply:",
            weather_final_response.content
        )

    else:

        # If the model doesn't request a tool,
        # its initial response is already the final response.

        print(
            "[Example 1 | manual tool call] Final reply:",
            weather_ai_message.content
        )


